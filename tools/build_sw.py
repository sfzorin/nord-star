#!/usr/bin/env python3
"""Write sw.js: precache list of every app file + a version hash of their contents.
Run after changing any app file:  python3 tools/build_sw.py
"""
import hashlib
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INCLUDE = ['index.html', 'manifest.webmanifest', 'icon.svg', 'css', 'js', 'vendor', 'data']
SKIP = re.compile(r'(^|/)\.|\.py$|\.md$')

files = []
for item in INCLUDE:
    p = os.path.join(ROOT, item)
    if os.path.isfile(p):
        files.append(item)
    else:
        for d, _, fs in os.walk(p):
            for f in fs:
                rel = os.path.relpath(os.path.join(d, f), ROOT)
                if not SKIP.search(rel):
                    files.append(rel)
files.sort()

h = hashlib.sha256()
for f in files:
    h.update(f.encode())
    h.update(open(os.path.join(ROOT, f), 'rb').read())
version = h.hexdigest()[:10]

# URLs exactly as the app requests them (module imports and the stylesheet carry ?v=N).
src = open(os.path.join(ROOT, 'index.html')).read()
vq = re.search(r'js/app\.js(\?v=\d+)', src)
q = vq.group(1) if vq else ''
urls = ['./']
for f in files:
    urls.append(f + q if (f.startswith('js/') and f.endswith('.js')) or f == 'css/app.css' else f)

sw = f"""// Generated by tools/build_sw.py — do not edit.
const VERSION = '{version}';
const CACHE = `nordstar-${{VERSION}}`;
const FILES = {urls!r};

self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
}});

self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys()
    .then((keys) => Promise.all(keys.filter((k) => k.startsWith('nordstar-') && k !== CACHE).map((k) => caches.delete(k))))
    .then(() => self.clients.claim()));
}});

// App files: cache first (works with no network). Page loads: the cached index.
// Anything else (online tiles, forecast): network only.
self.addEventListener('fetch', (e) => {{
  const url = new URL(e.request.url);
  if (url.origin !== location.origin) return;
  if (e.request.mode === 'navigate') {{
    e.respondWith(caches.match('index.html', {{ cacheName: CACHE }}).then((r) => r || fetch(e.request)));
    return;
  }}
  e.respondWith(caches.match(e.request, {{ cacheName: CACHE }}).then((r) => r || fetch(e.request)));
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
print(f'sw.js: {len(urls)} files, version {version}')
